/**
 * GitHub Copilot adapter.
 *
 * The Claude Code sources (commands/, agents/, skills/) are canonical. This module renders the
 * GitHub Copilot equivalents from them, so the two never drift by hand:
 *
 *   commands/speckit.X.md  -> .github/skills/sdd-speckit-X/SKILL.md   (user-invoked phase skill)
 *   agents/X.md            -> .github/agents/X.agent.md               (custom agent, tier + tools)
 *   skills/X/              -> .github/skills/X/                       (Agent Skills format is shared)
 *   hooks                  -> .github/hooks/sdd-speckit.json          (constitution guard, changelog)
 *   (generated)            -> .github/copilot-instructions.md         (marked block, merged)
 *   templates, scripts...  -> .specify/sdd-speckit/                   (what ${CLAUDE_PLUGIN_ROOT} was)
 *
 * Everything here is pure: renderCopilot() returns [{ path, content: Buffer }] and touches nothing.
 * writeCopilot() and checkCopilot() are the only functions that read or write a target directory.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";

export const INSTRUCTIONS_PATH = ".github/copilot-instructions.md";
export const BLOCK_BEGIN = "<!-- sdd-speckit:begin (generated by sdd-speckit-framework; edit outside this block) -->";
export const BLOCK_END = "<!-- sdd-speckit:end -->";

export function loadAdapter(frameworkRoot) {
  return JSON.parse(readFileSync(join(frameworkRoot, "adapters", "copilot", "adapter.json"), "utf8"));
}

/* ------------------------------------------------------------ frontmatter */

function parseScalar(raw) {
  const v = raw.trim();
  if (v.startsWith("[") && v.endsWith("]")) {
    const inner = v.slice(1, -1).trim();
    if (!inner) return [];
    return inner.split(",").map((s) => s.trim().replace(/^["']|["']$/g, ""));
  }
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) return v.slice(1, -1);
  return v;
}

/** Parses the flat `key: value` frontmatter these sources use. Nested YAML is not needed. */
export function parseFrontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(text);
  if (!m) return { data: {}, body: text };
  const data = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i <= 0 || /^\s/.test(line)) continue;
    data[line.slice(0, i).trim()] = parseScalar(line.slice(i + 1));
  }
  return { data, body: text.slice(m[0].length) };
}

function yamlValue(v) {
  if (Array.isArray(v)) return `[${v.map((x) => JSON.stringify(x)).join(", ")}]`;
  if (typeof v === "boolean") return String(v);
  return JSON.stringify(String(v));
}

function frontmatter(obj) {
  const lines = Object.entries(obj)
    .filter(([, v]) => v !== undefined && v !== null)
    .map(([k, v]) => `${k}: ${yamlValue(v)}`);
  return `---\n${lines.join("\n")}\n---\n`;
}

/* ---------------------------------------------------------- text rewrites */

/**
 * Sources may carry assistant-specific passages:
 *   <!-- claude-only:start --> ... <!-- claude-only:end -->   dropped for Copilot
 *   <!-- copilot-only ... -->                                 unwrapped for Copilot, verbatim
 * Claude Code reads the source as is, so it never sees the Copilot text as live instructions.
 */
export function rewriteText(text, adapter, { agentRenames = {} } = {}) {
  const support = adapter.supportDir;
  const prefix = adapter.commandSkillPrefix;

  let out = text.replace(/<!-- claude-only:start -->[\s\S]*?<!-- claude-only:end -->\n?/g, "");

  // Protect Copilot-only passages from the rewrites below, then restore them unwrapped.
  const kept = [];
  out = out.replace(/<!-- copilot-only\n([\s\S]*?)-->\n?/g, (_, body) => {
    kept.push(body);
    return `\u0000KEEP${kept.length - 1}\u0000`;
  });

  out = out
    .replaceAll("${CLAUDE_PLUGIN_ROOT}/", `${support}/`)
    .replaceAll("${CLAUDE_PLUGIN_ROOT}", support)
    .replace(/\/sdd-speckit:speckit\.([a-z]+)/g, `/${prefix}$1`)
    .replace(/(^|[\s`(*])\/speckit\.([a-z]+)/g, `$1/${prefix}$2`)
    .replace(/`\$ARGUMENTS`/g, "the arguments given after the command")
    .replace(/\$ARGUMENTS/g, "the arguments given after the command")
    .replace(/\bsubagents\b/g, "custom agents")
    .replace(/\bsubagent\b/g, "custom agent")
    .replace(/\bSubagents\b/g, "Custom agents")
    .replace(/\bSubagent\b/g, "Custom agent");

  for (const [from, to] of Object.entries(agentRenames)) {
    out = out.replace(new RegExp(`\\*\\*${from}\\*\\*`, "g"), `**${to}**`);
  }

  out = out.replace(/\u0000KEEP(\d+)\u0000/g, (_, i) => kept[Number(i)]);
  return out;
}

const FORBIDDEN = [/CLAUDE_PLUGIN_ROOT/, /\/sdd-speckit:/, /claude-only:start/, /<!-- copilot-only/];

function assertClean(path, text) {
  for (const re of FORBIDDEN) {
    if (re.test(text)) throw new Error(`copilot render: ${path} still contains ${re}`);
  }
}

/* -------------------------------------------------------------- mappings */

export function mapTools(adapter, tools = [], disallowed = []) {
  const deny = new Set(disallowed);
  const out = [];
  for (const t of tools) {
    if (deny.has(t)) continue;
    const mapped = adapter.tools[t];
    // One Copilot alias can cover several Claude tools. It is kept while any covered tool is allowed.
    if (mapped && !out.includes(mapped)) out.push(mapped);
  }
  return out;
}

export function mapModel(adapter, tier) {
  return tier ? adapter.models?.[tier] ?? null : null;
}

function generatedNote(source) {
  return `<!-- Generated from ${source} by sdd-speckit-framework. Edit the source, then re-run --emit=copilot. -->\n\n`;
}

/* ------------------------------------------------------------------ files */

function walk(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (e.isFile() && e.name !== ".DS_Store") out.push(p);
  }
  return out;
}

const posix = (p) => p.split(sep).join("/");

/* ---------------------------------------------------------------- render */

function renderAgents(frameworkRoot, adapter, readonlyVariants) {
  const files = [];
  const dir = join(frameworkRoot, "agents");
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".md")).sort()) {
    const src = readFileSync(join(dir, f), "utf8");
    const { data, body } = parseFrontmatter(src);
    const name = data.name ?? f.replace(/\.md$/, "");
    const baseDisallowed = data.disallowedTools ?? [];

    const emit = (agentName, description, disallowed, extra = {}) => {
      const fm = {
        name: agentName,
        description,
        tools: mapTools(adapter, data.tools ?? [], disallowed),
        model: mapModel(adapter, data.model) ?? undefined,
        ...extra,
      };
      const text = frontmatter(fm) + "\n" + generatedNote(`agents/${f}`) + rewriteText(body, adapter).replace(/^\n+/, "");
      const path = `.github/agents/${agentName}.agent.md`;
      assertClean(path, text);
      files.push({ path, content: Buffer.from(text) });
    };

    emit(name, data.description ?? "", baseDisallowed);

    for (const v of readonlyVariants.filter((r) => r.agent === name)) {
      emit(
        `${name}-readonly`,
        `Read-only variant of ${name} for /${adapter.commandSkillPrefix}${v.command.replace(/^speckit\./, "")}: ${v.denied.join(", ")} removed. ${data.description ?? ""}`.trim(),
        [...new Set([...baseDisallowed, ...v.denied])],
        { "user-invocable": false }
      );
    }
  }
  return files;
}

function readonlyVariantsFor(frameworkRoot, adapter) {
  const out = [];
  const dir = join(frameworkRoot, "commands");
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".md")).sort()) {
    const { data } = parseFrontmatter(readFileSync(join(dir, f), "utf8"));
    const command = data.name ?? f.replace(/\.md$/, "");
    const denied = data["disallowed-tools"] ?? [];
    if (!denied.length) continue;
    for (const agent of adapter.routing[command]?.agents ?? []) out.push({ command, agent, denied });
  }
  return out;
}

function renderCommandSkills(frameworkRoot, adapter) {
  const files = [];
  const dir = join(frameworkRoot, "commands");
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".md")).sort()) {
    const { data, body } = parseFrontmatter(readFileSync(join(dir, f), "utf8"));
    const command = data.name ?? f.replace(/\.md$/, "");
    const phase = command.replace(/^speckit\./, "");
    const skillName = `${adapter.commandSkillPrefix}${phase}`;
    const route = adapter.routing[command] ?? { agents: [] };
    const readonly = (data["disallowed-tools"] ?? []).length > 0;
    const agents = route.agents.map((a) => (readonly ? `${a}-readonly` : a));
    const renames = readonly ? Object.fromEntries(route.agents.map((a) => [a, `${a}-readonly`])) : {};

    const lines = [];
    lines.push(`> **SDD Speckit phase \`${phase}\`.** Model tier: **${data.model ?? "any"}**.`);
    if (agents.length) {
      lines.push(
        `> Run the phase work in the custom agent${agents.length > 1 ? "s" : ""} ${agents.map((a) => `**${a}**`).join(", ")} ` +
          "(`.github/agents/`) as a subagent. The agent pins the model tier and the tool set."
      );
    }
    if (readonly) {
      lines.push(
        `> **Read-only.** ${agents.map((a) => `**${a}**`).join(", ")} has no file-editing tool. Do not edit files ` +
          "in the main conversation either: produce the report and stop."
      );
    }

    const fm = {
      name: skillName,
      description: data.description ?? "",
      "argument-hint": data["argument-hint"],
      // A phase is a deliberate act, as a Claude Code slash command is. The model must not start one.
      "disable-model-invocation": true,
    };
    const text =
      frontmatter(fm) + "\n" + generatedNote(`commands/${f}`) + lines.join("\n") + "\n\n" +
      rewriteText(body, adapter, { agentRenames: renames }).replace(/^\n+/, "");
    const path = `.github/skills/${skillName}/SKILL.md`;
    assertClean(path, text);
    files.push({ path, content: Buffer.from(text) });
  }
  return files;
}

function renderSkills(frameworkRoot, adapter) {
  const files = [];
  const dir = join(frameworkRoot, "skills");
  const exclude = new Set(adapter.excludeSkills ?? []);
  for (const name of readdirSync(dir).sort()) {
    if (exclude.has(name) || !statSync(join(dir, name)).isDirectory()) continue;
    for (const abs of walk(join(dir, name))) {
      const rel = posix(relative(dir, abs));
      const path = `.github/skills/${rel}`;
      let content = readFileSync(abs);
      if (abs.endsWith(".md")) {
        const text = rewriteText(content.toString("utf8"), adapter);
        assertClean(path, text);
        content = Buffer.from(text);
      }
      files.push({ path, content });
    }
  }
  return files;
}

function renderSupport(frameworkRoot, adapter) {
  const files = [];
  for (const entry of adapter.supportCopy) {
    const abs = join(frameworkRoot, entry);
    if (!existsSync(abs)) continue;
    const list = statSync(abs).isDirectory() ? walk(abs) : [abs];
    for (const f of list) {
      const rel = posix(relative(frameworkRoot, f));
      let content = readFileSync(f);
      if (f.endsWith(".md")) content = Buffer.from(rewriteText(content.toString("utf8"), adapter));
      files.push({ path: `${adapter.supportDir}/${rel}`, content });
    }
  }
  return files;
}

function renderHooks(adapter) {
  const script = (path) => `sh ${adapter.supportDir}/scripts/${path}`;
  // No matcher: Copilot's tool names differ between the CLI, the cloud agent and VS Code. Each
  // script filters on the tool name and path itself, so it is safe to run on every tool call.
  // The gate runner applies the modes in .specify/sdd-speckit.json; hook.sh is its entry point.
  const hooks = {
    version: 1,
    hooks: {
      preToolUse: [{ type: "command", bash: script("harness/hook.sh pre"), cwd: ".", timeoutSec: 15 }],
      postToolUse: [
        { type: "command", bash: script("hooks/log-artifact-change.sh"), cwd: ".", timeoutSec: 10 },
        { type: "command", bash: script("harness/hook.sh post"), cwd: ".", timeoutSec: 30 },
      ],
    },
  };
  return [{ path: ".github/hooks/sdd-speckit.json", content: Buffer.from(JSON.stringify(hooks, null, 2) + "\n") }];
}

export function instructionsBlock(frameworkRoot, adapter) {
  const p = adapter.commandSkillPrefix;
  const cmdDir = join(frameworkRoot, "commands");
  const rows = [];
  for (const f of readdirSync(cmdDir).filter((n) => n.endsWith(".md")).sort(phaseOrder)) {
    const { data } = parseFrontmatter(readFileSync(join(cmdDir, f), "utf8"));
    const command = data.name ?? f.replace(/\.md$/, "");
    const route = adapter.routing[command] ?? { agents: [] };
    const readonly = (data["disallowed-tools"] ?? []).length > 0;
    const agents = route.agents.map((a) => `\`${readonly ? `${a}-readonly` : a}\``).join(", ") || "none";
    rows.push(`| \`/${p}${command.replace(/^speckit\./, "")}\` | ${route.writes ?? ""} | ${agents} | ${data.model ?? ""} |`);
  }

  return [
    BLOCK_BEGIN,
    "# Spec-Driven Development (SDD Speckit)",
    "",
    "This repository follows Spec-Driven Development. Features move through phases, and each phase",
    "reads what the phase before it wrote:",
    "",
    "```",
    "constitution → specify → clarify → plan → checklist → tasks → analyze → implement → converge",
    "```",
    "",
    "| Run | Writes | Custom agent | Tier |",
    "|---|---|---|---|",
    ...rows,
    "",
    "## Rules",
    "",
    `- **\`specify\` comes before \`plan\`.** It is the only strict ordering rule. \`clarify\`, \`checklist\` and \`analyze\` are quality gates.`,
    `- **Never edit \`.specify/memory/constitution.md\` directly.** Amend it with \`/${p}constitution\`. A \`preToolUse\` hook (\`.github/hooks/sdd-speckit.json\`) blocks other writes. It guards against accidents. It is not a security boundary.`,
    `- **\`/${p}analyze\` is read-only.** It produces a report and changes nothing.`,
    `- **Onboarding.** Run \`/${p}onboard\` once. An existing codebase (brownfield) then goes \`/${p}discover\` → \`/${p}constitution\` → \`/${p}baseline\` before the feature phases.`,
    "- **Harness gates.** `.specify/sdd-speckit.json` sets each gate to `off`, `warn` or `block`. The same runner (`.specify/sdd-speckit/scripts/harness/gate.py`) checks writes in the hook and pull requests in CI. When a gate stops a write, fix the cause; do not route around it.",
    "- When a phase skill names a custom agent, run the work in that agent as a subagent. It pins the model tier and the tool set.",
    `- Templates are in \`${adapter.supportDir}/templates/\`. A composed template in \`.specify/templates/overrides/\` (base + industry profile + stack profile) wins over the base template.`,
    "- The project's framework choices (mode, industry, stack, assistants, MCP connectors, editor, gates) are recorded in `.specify/sdd-speckit.json`.",
    "- Requirements go in `spec.md` and say what and why, never how. Technology choices go in `plan.md`, each with the alternative it rejected.",
    "- Write tests before the implementation they cover.",
    BLOCK_END,
    "",
  ].join("\n");
}

const PHASE_ORDER = ["onboard", "discover", "constitution", "baseline", "specify", "clarify", "plan", "checklist", "tasks", "analyze", "implement", "converge", "taskstoissues", "status", "setup"];
function phaseOrder(a, b) {
  const ia = PHASE_ORDER.indexOf(a.replace(/^speckit\.|\.md$/g, ""));
  const ib = PHASE_ORDER.indexOf(b.replace(/^speckit\.|\.md$/g, ""));
  return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib) || a.localeCompare(b);
}

/** Every Copilot file, as [{ path, content: Buffer }], sorted by path. Writes nothing. */
export function renderCopilot(frameworkRoot) {
  const adapter = loadAdapter(frameworkRoot);
  const files = [
    ...renderCommandSkills(frameworkRoot, adapter),
    ...renderAgents(frameworkRoot, adapter, readonlyVariantsFor(frameworkRoot, adapter)),
    ...renderSkills(frameworkRoot, adapter),
    ...renderHooks(adapter),
    ...renderSupport(frameworkRoot, adapter),
    { path: INSTRUCTIONS_PATH, content: Buffer.from(instructionsBlock(frameworkRoot, adapter)) },
  ];

  const seen = new Set();
  for (const f of files) {
    if (seen.has(f.path)) throw new Error(`copilot render: two sources produce ${f.path}`);
    seen.add(f.path);
  }
  return files.sort((a, b) => a.path.localeCompare(b.path));
}

/* ------------------------------------------------------------ write/check */

/** Replaces the marked block in an existing instructions file, or appends it. Other text is kept. */
export function mergeInstructions(existing, block) {
  if (existing == null || existing === "") return block;
  const start = existing.indexOf(BLOCK_BEGIN);
  const end = existing.indexOf(BLOCK_END);
  if (start !== -1 && end > start) {
    let after = existing.slice(end + BLOCK_END.length);
    if (after.startsWith("\n")) after = after.slice(1);
    return existing.slice(0, start) + block + after;
  }
  return existing.replace(/\n*$/, "\n\n") + block;
}

function desiredContent(target, f) {
  if (f.path !== INSTRUCTIONS_PATH) return f.content;
  const p = join(target, f.path);
  const existing = existsSync(p) ? readFileSync(p, "utf8") : null;
  return Buffer.from(mergeInstructions(existing, f.content.toString("utf8")));
}

export function writeCopilot(target, files, { dryRun }) {
  const log = [];
  const groups = {};
  for (const f of files) {
    const parts = f.path.split("/");
    const key = parts.length > 2 ? `${parts.slice(0, 2).join("/")}/` : f.path;
    groups[key] = (groups[key] ?? 0) + 1;
    if (dryRun) continue;
    const p = join(target, f.path);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, desiredContent(target, f));
  }
  for (const [k, n] of Object.entries(groups).sort()) {
    log.push(`${dryRun ? "would write" : "wrote"} copilot: ${k}${k.endsWith("/") ? ` (${n} file${n > 1 ? "s" : ""})` : ""}`);
  }
  return log;
}

/**
 * Compares a directory with a fresh render. Returns the list of differences; empty means in sync.
 * An extra file is reported only inside a path the render owns, so a real project's own files
 * are not noise. `strict` reports every extra file: that is the check for adapters/copilot/dist/.
 */
export function checkCopilot(dir, files, { strict = false } = {}) {
  const diffs = [];
  const want = new Map(files.map((f) => [f.path, desiredContent(dir, f)]));
  for (const [path, content] of want) {
    const p = join(dir, path);
    if (!existsSync(p)) diffs.push(`missing  ${path}`);
    else if (!readFileSync(p).equals(content)) diffs.push(`changed  ${path}`);
  }
  const owned = ownedPrefixes(files);
  if (existsSync(dir)) {
    for (const abs of walk(dir)) {
      const rel = posix(relative(dir, abs));
      if (want.has(rel)) continue;
      if (strict || owned.some((p) => rel.startsWith(p))) diffs.push(`extra    ${rel}`);
    }
  }
  return diffs;
}

/** Directories wholly produced by the render: the support dir, and each rendered skill folder. */
function ownedPrefixes(files) {
  const out = new Set();
  for (const { path } of files) {
    const parts = path.split("/");
    if (parts[0] === ".specify" && parts[1] === "sdd-speckit") out.add(".specify/sdd-speckit/");
    if (parts[0] === ".github" && parts[1] === "skills" && parts.length > 3) out.add(`.github/skills/${parts[2]}/`);
  }
  return [...out];
}
